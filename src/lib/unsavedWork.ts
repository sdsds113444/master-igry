/** Флаг «на странице есть несохранённая работа» — общий на приложение.
 *
 *  Зачем понадобился: защита от потери проставленных баллов в админке стояла только на
 *  beforeunload (закрытие/перезагрузка вкладки) и на смене игры внутри страницы. Выход из
 *  аккаунта — это навигация внутри SPA, beforeunload на неё не срабатывает: Admin просто
 *  размонтируется вместе со всем введённым. Иконка «Выйти» в шапке без подписи и стоит
 *  вплотную к переключателю темы, так что один промах уносил вечер оценивания.
 *
 *  Почему модульная переменная, а не контекст: флаг нужен ровно в двух местах (страница,
 *  которая его ставит, и шапка, которая его читает), живёт вне React-дерева и не должен
 *  вызывать перерисовку. Контекст ради этого — лишний провод через всё приложение.
 *
 *  Ставящая сторона обязана снимать флаг в cleanup эффекта: тогда он сам гаснет и при
 *  сохранении, и при уходе со страницы, и «мёртвый» флаг не заставит шапку спрашивать
 *  подтверждение там, где терять уже нечего. */
let unsaved = false

export function setUnsavedWork(value: boolean): void {
  unsaved = value
}

export function hasUnsavedWork(): boolean {
  return unsaved
}
