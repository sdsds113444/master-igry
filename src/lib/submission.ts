/** Что считается сдачей и что показывать после дедлайна.
 *
 *  Вынесено из TeamCabinet отдельным модулем ради тестов: цена ошибки здесь —
 *  команда думает, что сдала, а в базе пусто, и узнаёт об этом уже по нулю за неделю.
 */

/** Серверный снимок сдачи: ровно то, что вернул getSubmission, и ничего больше. */
export type SavedSubmission = { answer: string; fileName: string | null }

/** Есть ли в тексте хоть одна буква или цифра. Одни знаки препинания/пробелы (например
 *  случайная запятая на мобильной клавиатуре) ответом НЕ считаются — иначе такой «ответ»
 *  проходил как сдача и показывал тренеру мусорную «точку». */
export function hasMeaningfulText(s: string): boolean {
  return /[\p{L}\p{N}]/u.test(s)
}

/** Реальная сдача = есть осмысленный текст ИЛИ прикреплённый файл. Пустая строка в
 *  answers (напр. выбрали файл, а его загрузку заблокировал корпоративный контур, и
 *  текста не было) сдачей НЕ считается — иначе при следующем заходе кабинет показывал бы
 *  ложное «Ответ отправлен» на пустой заготовке, хотя команде сдавать ещё нечего. */
export function isRealSubmission(answer: string, fileName: string | null): boolean {
  return hasMeaningfulText(answer) || !!fileName
}

/** Лежит ли в базе настоящая сдача. Принимает ТОЛЬКО серверный снимок.
 *
 *  Отдельная функция, чтобы физически нельзя было передать сюда черновик: раньше экран
 *  закрытого дедлайна судил по состоянию textarea и по имени локально выбранного файла,
 *  из-за чего набранный, но не отправленный ответ объявлялся сохранённым. */
export function hasServerSubmission(saved: SavedSubmission | null): boolean {
  return !!saved && isRealSubmission(saved.answer, saved.fileName)
}

/** Остался ли в поле осмысленный текст, которого НЕТ в базе.
 *
 *  Нужен, чтобы после дедлайна честно сказать «этот текст не был отправлен», а не прятать
 *  его: молча стереть черновик так же плохо, как выдать его за сданный. */
export function hasUnsentDraft(answer: string, saved: SavedSubmission | null): boolean {
  return hasMeaningfulText(answer) && answer !== (saved?.answer ?? '')
}
